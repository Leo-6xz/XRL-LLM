function [expl, meta] = generateLayeredExplanations(record, llm, cfg, feeder, opts)
%GENERATELAYEREDEXPLANATIONS  Produce all three audience levels for one decision.
%
%   [EXPL, META] = GENERATELAYEREDEXPLANATIONS(RECORD, LLM, CFG, FEEDER)
%
%   EXPL has fields .summary, .standard and .detailed, matching the three
%   audiences in the brief:
%
%     summary   one sentence   shift dispatcher, read at a glance
%     standard  2-3 sentences  system engineer, includes attribution
%     detailed  a paragraph    planning staff, includes alternatives and risk
%
%   ONE CONSISTENCY REQUIREMENT WORTH ENFORCING
%   -------------------------------------------
%   The three levels are generated by three independent calls, so nothing
%   stops the model from asserting one cause in the summary and a different
%   one in the detailed text. That inconsistency is exactly what an
%   operator will notice and it is fatal to trust. META.CONSISTENT reports
%   whether the top attributed factor is named in all three levels; treat a
%   false as a defect to investigate, not a cosmetic issue. If it recurs,
%   generate the detailed level first and pass it as context to the other
%   two rather than generating independently.

if nargin < 5 || isempty(opts), opts = struct(); end
if ~isfield(opts,'singleCall'), opts.singleCall = true; end

% -------------------------------------------------------------------
% SINGLE-CALL MODE (default)
% -------------------------------------------------------------------
% Generating the three levels in one request instead of three cuts
% latency by roughly 3x, and -- more importantly -- removes the
% consistency problem described below at the source: one generation
% cannot contradict itself about which factor was decisive, whereas
% three independent ones routinely do.
%
% Falls back to three separate calls if the reply cannot be parsed.
if opts.singleCall && llm.available
    try
        [expl, meta] = singleCallLayered(record, llm, cfg, feeder);
        return
    catch ME
        % Count rather than warn per record: on an 84-record run the same
        % warning 84 times buries everything else in the log.
        persistent nFallback nTotal
        if isempty(nFallback), nFallback = 0; nTotal = 0; end
        nFallback = nFallback + 1; nTotal = nTotal + 1;
        if nFallback == 1 || mod(nFallback, 25) == 0
            warning('generateLayeredExplanations:singleCallFailed', ...
                ['Single-call generation failed %d time(s) (last: %s). ', ...
                 'Falling back to three calls, which is ~3x slower. If this ', ...
                 'persists, the model is not honouring the tag format -- ', ...
                 'try a lower cfg.llm.temperature or a different model.'], ...
                nFallback, ME.message);
        end
    end
end

levels = {'summary','standard','detailed'};
expl = struct();
meta = struct();
totalLatency = 0;

for i = 1:numel(levels)
    L = levels{i};
    [txt, m] = generateExplanation(record, llm, cfg, feeder, L, 'full');
    expl.(L)  = txt;
    meta.(L)  = m;
    totalLatency = totalLatency + m.latencySec;
end

meta.totalLatencySec = totalLatency;
meta.backend         = meta.standard.backend;

% Consistency check on the top attributed factor.
topName = lower(record.topFeatures(1).name);
key = firstContentWord(topName);
meta.consistent = ~isempty(key) && ...
    contains(lower(expl.standard), key) && contains(lower(expl.detailed), key);
end

% =====================================================================
function [expl, meta] = singleCallLayered(record, llm, cfg, feeder)
%SINGLECALLLAYERED  All three audience levels from one generation.

base = promptTemplates(record, cfg, feeder, 'standard', 'full');

% Replace the single-level task block with a three-level one.
cut = strfind(base, '[TASK]');
if isempty(cut)
    error('singleCallLayered:noTask', 'Prompt has no [TASK] block.');
end
context = base(1:cut(1)-1);

task = [ ...
    '[TASK]\n' ...
    'Write THREE explanations of the decision above, for three audiences.\n' ...
    'They must agree with each other on which factor was decisive.\n\n' ...
    'Use exactly this format, with no other text before or after:\n\n' ...
    '<SUMMARY>\n' ...
    'One sentence, maximum 25 words, for a shift dispatcher: what was done\n' ...
    'and the single main reason.\n' ...
    '</SUMMARY>\n' ...
    '<STANDARD>\n' ...
    'Two to three sentences for a system engineer: why the action was taken,\n' ...
    'which factors were decisive per the attribution, and the expected effect.\n' ...
    '</STANDARD>\n' ...
    '<DETAILED>\n' ...
    'One paragraph of 120-180 words for a planning engineer: the causal chain,\n' ...
    'the decisive factors and their weight, the quantitative expected effect,\n' ...
    'the alternatives available and why this action fits better, and any\n' ...
    'residual risk if conditions change.\n' ...
    '</DETAILED>\n\n' ...
    '[RULES]\n' ...
    '  - Use ONLY the numbers given above. Do not invent voltages or buses.\n' ...
    '  - If the attribution shows no dominant factor, say so.\n' ...
    '  - No preamble, no markdown, no bullet points.\n' ...
    '  - Your reply must begin with the characters <SUMMARY> and nothing else.\n\n' ...
    '[EXAMPLE OF THE REQUIRED FORMAT]\n' ...
    '<SUMMARY>\n' ...
    'Raised the tap one step because the feeder end had fallen to 0.9606 p.u.\n' ...
    '</SUMMARY>\n' ...
    '<STANDARD>\n' ...
    'The controller raised the tap because ... The decisive factor was ...\n' ...
    'The expected effect is ...\n' ...
    '</STANDARD>\n' ...
    '<DETAILED>\n' ...
    'Under the conditions above ...\n' ...
    '</DETAILED>\n'];

prompt = [context sprintf(task)];

t0 = tic;
raw = char(generate(llm.chat, prompt));
elapsed = toc(t0);

expl.summary  = extractTag(raw, 'SUMMARY');
expl.standard = extractTag(raw, 'STANDARD');
expl.detailed = extractTag(raw, 'DETAILED');

if isempty(expl.summary) || isempty(expl.standard) || isempty(expl.detailed)
    error('singleCallLayered:parseFailed', ...
        'Reply did not contain all three tagged sections.');
end

meta.summary  = struct('backend',llm.backend,'latencySec',elapsed/3,'fallback',false,'prompt',prompt);
meta.standard = meta.summary;
meta.detailed = meta.summary;
meta.totalLatencySec = elapsed;
meta.backend         = llm.backend;
meta.singleCall      = true;
meta.nPromptChars    = numel(prompt);

topName = lower(record.topFeatures(1).name);
key = firstContentWord(topName);
meta.consistent = ~isempty(key) && ...
    contains(lower(expl.standard), key) && contains(lower(expl.detailed), key);
end

% =====================================================================
function t = extractTag(raw, tag)
%EXTRACTTAG  Pull one tagged section out of a multi-section reply.
%
%   An 8B model asked for <SUMMARY>...</SUMMARY> will comply most of the
%   time and then, unpredictably, emit "**SUMMARY:**", "### SUMMARY",
%   "SUMMARY -" or an unclosed tag. Insisting on the exact format sent
%   every one of those to the three-call fallback, tripling the runtime of
%   the whole stage for a purely cosmetic mismatch.
%
%   The patterns below are tried in order of strictness. Prompt harder AND
%   parse looser -- with a small local model you need both.
raw = char(raw);

pats = { ...
    ['<'   tag '>(.*?)</' tag '>'], ...            % <TAG>...</TAG>
    ['\['  tag '\](.*?)\[/' tag '\]'], ...        % [TAG]...[/TAG]
    ['<'   tag '>(.*?)(?=<[A-Z_]+>|$)'], ...       % unclosed <TAG>
    ['\*\*\s*' tag '\s*:?\s*\*\*(.*?)(?=\*\*\s*[A-Z_]+|$)'], ... % **TAG:**
    ['#+\s*' tag '\s*:?(.*?)(?=#+\s*[A-Z_]+|$)'], ...  % ### TAG
    ['(?:^|\n)\s*' tag '\s*[:\-]\s*(.*?)(?=\n\s*[A-Z_]{4,}\s*[:\-]|$)'] };  % TAG:

t = '';
for i = 1:numel(pats)
    m = regexp(raw, pats{i}, 'tokens', 'once', 'ignorecase', 'dotexceptnewline');
    if isempty(m)
        m = regexp(raw, pats{i}, 'tokens', 'once', 'ignorecase');
    end
    if ~isempty(m) && ~isempty(strtrim(m{1}))
        t = stripPreamble(strtrim(m{1}));
        return
    end
end
end

% =====================================================================
function w = firstContentWord(s)
%FIRSTCONTENTWORD  A distinctive token to search for across levels.
tok = regexp(s, '[a-z]{4,}', 'match');
stop = {'bus','buses','value','level','feeder'};
tok = tok(~ismember(tok, stop));
if isempty(tok), w = ''; else, w = tok{1}; end
end
