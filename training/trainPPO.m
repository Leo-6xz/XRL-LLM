function [agent, trainingStats, env] = trainPPO(cfg, feeder)
%TRAINPPO  Train the PPO Volt/VAR controller.
%
%   [AGENT, STATS, ENV] = TRAINPPO(CFG, FEEDER)
%
%   Trains for CFG.TRAIN.MAXEPISODES episodes and saves the agent to
%   CFG.TRAIN.SAVEPATH. Returns the trained agent, the training statistics
%   and the environment (reused downstream so evaluation runs against the
%   same feeder object).
%
%   WHAT TO WATCH DURING TRAINING
%   -----------------------------
%   The total reward curve alone is not diagnostic here, because four
%   objectives are summed into it. Use PLOTTRAININGPROGRESS afterwards, or
%   watch these in the episode manager:
%
%     * Episode reward should rise steeply for ~300 episodes as the agent
%       discovers the OLTC, then improve slowly as it learns capacitor
%       coordination. A curve that plateaus immediately near -20 usually
%       means the entropy weight is too low and the policy collapsed.
%     * If reward oscillates violently, lower cfg.ppo.actorLR before
%       touching anything else.
%     * If the violation rate falls but the interpretability penalty
%       climbs, the agent is buying voltage performance with unexplainable
%       actions -- raise cfg.reward.delta.
%
%   EXPECTED COST
%   -------------
%   One environment step is one power-flow solve (~0.3 ms) plus the
%   penalty computation. 3000 episodes x 24 steps is ~72k steps, which
%   runs in the order of minutes on a laptop. This is only feasible
%   because the environment is the native solver rather than Simscape;
%   see RADIALPOWERFLOW for the reasoning.
%
%   See also CREATEPPOAGENT, XRL33ENV, XRLCONFIG.

if nargin < 1 || isempty(cfg),    cfg = xrlConfig(); end
if nargin < 2 || isempty(feeder), feeder = buildFeeder(cfg.net.dataFcn()); end

rng(cfg.seed);

% ---------------------------------------------------------------------
% Environment and agent
% ---------------------------------------------------------------------
env = XRL33Env(cfg, feeder);
obsInfo = getObservationInfo(env);
actInfo = getActionInfo(env);

agent = createPPOAgent(obsInfo, actInfo, cfg);

% ---------------------------------------------------------------------
% Training options
% ---------------------------------------------------------------------
saveDir = fileparts(cfg.train.savePath);
if ~isempty(saveDir) && ~exist(saveDir, 'dir')
    mkdir(saveDir);
end

trainOpts = rlTrainingOptions( ...
    'MaxEpisodes',                cfg.train.maxEpisodes, ...
    'MaxStepsPerEpisode',         cfg.episode.stepsPerEpisode, ...
    'ScoreAveragingWindowLength', cfg.train.scoreAveragingLen, ...
    'StopTrainingCriteria',       'AverageReward', ...
    'StopTrainingValue',          cfg.train.stopValue, ...
    'SaveAgentCriteria',          'AverageReward', ...
    'SaveAgentValue',             cfg.train.checkpointThreshold, ...
    'SaveAgentDirectory',         fullfile(saveDir, 'checkpoints'), ...
    'Verbose',                    cfg.io.verbose, ...
    'Plots',                      cfg.train.plots);

% ---------------------------------------------------------------------
% Parallel training. Note the deliberate choice of SYNC over ASYNC:
% PPO is on-policy, so asynchronous workers submit experience generated by
% a stale policy, which biases the importance ratio. MATLAB permits it,
% but for an on-policy method 'sync' is the correct setting.
% ---------------------------------------------------------------------
if cfg.train.useParallel
    if isempty(ver('parallel'))
        warning('trainPPO:noPCT', ...
            'Parallel Computing Toolbox not found; training on a single worker.');
    else
        trainOpts.UseParallel = true;
        trainOpts.ParallelizationOptions.Mode = 'sync';
        trainOpts.ParallelizationOptions.WorkerRandomSeeds = -1;
        if isprop(trainOpts.ParallelizationOptions, 'NumWorkers')
            trainOpts.ParallelizationOptions.NumWorkers = cfg.train.numWorkers;
        end
    end
end

% ---------------------------------------------------------------------
% Train
% ---------------------------------------------------------------------
if cfg.io.verbose
    fprintf('\n=== Training PPO: %d episodes x %d steps ===\n', ...
        cfg.train.maxEpisodes, cfg.episode.stepsPerEpisode);
    fprintf('Reward weights: alpha=%.3g beta=%.3g gamma=%.3g delta=%.3g\n', ...
        cfg.reward.alpha, cfg.reward.beta, cfg.reward.gamma, cfg.reward.delta);
end

tStart = tic;
trainingStats = train(agent, env, trainOpts);
elapsed = toc(tStart);

% ---------------------------------------------------------------------
% Save
% ---------------------------------------------------------------------
% ---------------------------------------------------------------------
% The FINAL agent is not necessarily the BEST agent. On the first healthy
% run the moving-average reward peaked near -2.5 around episode 1500-1900
% and drifted back to -3.7 by episode 3000 -- so saving the last policy
% discarded roughly a third of the performance that had been reached.
% PPO on a stochastic-scenario environment oscillates; take the best
% checkpoint, not the last one.
[bestAvg, bestEp] = bestWindow(trainingStats.EpisodeReward, cfg.train.scoreAveragingLen);
saveStruct.bestEpisode    = bestEp;
saveStruct.bestAvgReward  = bestAvg;
saveStruct.finalAvgReward = mean(trainingStats.EpisodeReward(max(1,end-cfg.train.scoreAveragingLen+1):end));

if cfg.io.verbose
    fprintf(['\n  Best %d-episode average: %.3f at episode %d\n' ...
             '  Final %d-episode average: %.3f\n'], ...
        cfg.train.scoreAveragingLen, bestAvg, bestEp, ...
        cfg.train.scoreAveragingLen, saveStruct.finalAvgReward);
    if bestAvg > saveStruct.finalAvgReward + 0.05*abs(bestAvg)
        fprintf(['  NOTE: the final policy is meaningfully worse than the best one\n' ...
                 '  reached during training. Consider LOADBESTCHECKPOINT.\n']);
    end
end

saveStruct.agent         = agent;         %#ok<STRNU>
saveStruct.cfg           = cfg;
saveStruct.trainingStats = trainingStats;
saveStruct.elapsedSec    = elapsed;
saveStruct.savedOn       = datetime('now');

% Never silently destroy a previous agent. Three separate agents were
% overwritten at this path during development, each a 10-minute run, and
% each time the loss was only noticed later when a comparison was wanted.
% Back up first; the file is small relative to the cost of retraining.
if exist(cfg.train.savePath, 'file')
    [d,f,x] = fileparts(cfg.train.savePath);
    backup = fullfile(d, sprintf('%s_backup_%s%s', f, datestr(now,'yyyymmdd_HHMMSS'), x));
    copyfile(cfg.train.savePath, backup);
    warning('trainPPO:overwrite', ...
        ['An agent already existed at %s. It has been backed up to %s.\n', ...
         'Use a distinct cfg.train.savePath per experiment to avoid this.'], ...
        cfg.train.savePath, backup);
end

save(cfg.train.savePath, '-struct', 'saveStruct');

% ---------------------------------------------------------------------
% Health check. A PPO run can complete every episode and still produce a
% dead policy; the reward curve alone will not tell you. This costs about
% a second and is the difference between finding out now and finding out
% after the explanation stages have run on a policy with nothing to say.
% ---------------------------------------------------------------------
try
    diag = diagnosePolicy(makePolicyFcn(agent, cfg), cfg, feeder, ...
        struct('nEpisodes', 5, 'verbose', cfg.io.verbose));
    if ~diag.healthy
        warning('trainPPO:policyCollapse', ...
            ['The trained policy failed its health check (frozen=%d, ', ...
             'saturated=%d, unresponsive=%d). Do NOT proceed to the ', ...
             'explanation stages. See the diagnostic output above.'], ...
            diag.frozen, diag.saturated, diag.unresponsive);
    end
catch ME
    warning('trainPPO:diagnosticFailed', ...
        'Policy diagnostic could not run: %s', ME.message);
end

if cfg.io.verbose
    fprintf('Training finished in %.1f s. Agent saved to %s\n', ...
        elapsed, cfg.train.savePath);
end
end

% =====================================================================
function [bestAvg, bestEp] = bestWindow(r, w)
%BESTWINDOW  Best trailing moving average of the episode reward.
r = r(:);
w = min(w, numel(r));
m = movmean(r, [w-1 0]);
m(1:w-1) = -Inf;                 % ignore partial windows at the start
[bestAvg, bestEp] = max(m);
end
